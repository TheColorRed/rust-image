//! Writes the parts of the bindings that follow the library's source, so they cannot drift from it.
//!
//! Every `pub fn name() -> Self` in the library's `colors_list.rs` becomes a `Color.name()` constructor. This is the same
//! scan the C bindings use (`build_ffi/color_list.rs` in the `abra` crate).

use regex::Regex;
use std::{env, fs, path::PathBuf};

fn main() {
  let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
  let colors_path = manifest_dir
    .join("..")
    .join("..")
    .join("abra")
    .join("core")
    .join("primitives")
    .join("src")
    .join("color")
    .join("colors_list.rs");
  let source = fs::read_to_string(&colors_path).unwrap_or_else(|_| panic!("Could not open {}", colors_path.display()));

  let pattern = Regex::new(r"pub\s+fn\s+([a-z0-9_]+)\s*\(\s*\)\s*->\s*Self").unwrap();
  let names: Vec<&str> = pattern.captures_iter(&source).map(|capture| capture.get(1).unwrap().as_str()).collect();
  if names.is_empty() {
    panic!("No color functions found in {}", colors_path.display());
  }

  let mut out = String::from("// Generated by build.rs from the library's colors_list.rs. Do not edit.\n");
  out.push_str("#[uniffi::export]\nimpl Color {\n");
  for name in names {
    out.push_str(&format!(
      "  #[uniffi::constructor]\n  pub fn {name}() -> Self {{\n    Self(abra::abra_core::Color::{name}())\n  }}\n"
    ));
  }
  out.push_str("}\n");
  fs::write(PathBuf::from(env::var("OUT_DIR").unwrap()).join("color_names.rs"), out).unwrap();

  println!("cargo:rerun-if-changed={}", colors_path.display());
  println!("cargo:rerun-if-changed=build.rs");
}
